// Generates src/version.ts from package.json so the SDK version header
// can never drift from the published version. Runs on `npm run build`.
const fs = require('fs')
const path = require('path')

const { version } = require('../package.json')
const target = path.join(__dirname, '..', 'src', 'version.ts')
const contents = `// AUTO-GENERATED by scripts/gen-version.js — do not edit by hand.\nexport const SDK_VERSION = '${version}'\n`

fs.writeFileSync(target, contents)
console.log(`src/version.ts -> ${version}`)
